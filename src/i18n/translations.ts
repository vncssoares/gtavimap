import { Language } from '@/types';

export const PRICING_CONFIG = {
  en: { monthly: 2.99, annual: 19.99 },
  'pt-BR': { monthly: 14.90, annual: 99.90 },
  es: { monthly: 2.99, annual: 19.99 },
} as const;

export function getAnnualDiscountPercent(lang: Language): number {
  const cfg = PRICING_CONFIG[lang] || PRICING_CONFIG.en;
  return Math.round((1 - cfg.annual / (cfg.monthly * 12)) * 100);
}

export function formatReviewDate(isoDate: string, lang: Language): string {
  try {
    const date = new Date(isoDate);
    const locale = lang === 'pt-BR' ? 'pt-BR' : lang === 'es' ? 'es-ES' : 'en-US';
    return date.toLocaleDateString(locale, {
      day: 'numeric',
      month: 'short',
      year: 'numeric',
    });
  } catch {
    return isoDate;
  }
}

